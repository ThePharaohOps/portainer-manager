(function () {
  if (typeof window === 'undefined') return;

  const LANGS = Object.keys(I18N);
  function detectLang() {
    try {
      const saved = localStorage.getItem('lang');
      if (LANGS.includes(saved)) return saved;
    } catch {}
    return /^fr\b/i.test(navigator.language || '') ? 'fr' : 'en';
  }

  const lang = detectLang();
  const locale = lang === 'fr' ? 'fr-FR' : 'en-US';
  const plural = new Intl.PluralRules(locale);

  function t(key, vars) {
    const s = I18N[lang][key] ?? I18N.fr[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => vars[k] ?? m) : s;
  }

  function tp(key, n, vars) {
    return t(`${key}.${plural.select(n) === 'one' ? 'one' : 'other'}`, { n, ...vars });
  }

  // Server errors carry a stable `code`; fall back to the server's message for unknown ones.
  function errorMessage(body, status) {
    if (body?.code && I18N[lang][`err.${body.code}`]) {
      const minutes = body.retryAfter ? Math.ceil(body.retryAfter / 60) : undefined;
      return t(`err.${body.code}`, { ...body, minutes });
    }
    return body?.error || t('err.http', { status });
  }

  function apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    for (const attr of ['placeholder', 'title', 'aria-label']) {
      root.querySelectorAll(`[data-i18n-${attr}]`).forEach(el => el.setAttribute(attr, t(el.getAttribute(`data-i18n-${attr}`))));
    }
  }

  function setLang(next) {
    try { localStorage.setItem('lang', next); } catch {}
    location.reload();
  }

  document.documentElement.lang = lang;
  window.i18n = { lang, locale, t, tp, errorMessage, apply, setLang };
  window.t = t;
  window.tp = tp;

  document.addEventListener('DOMContentLoaded', () => {
    apply();
    const toggle = document.getElementById('langToggle');
    if (toggle) toggle.addEventListener('click', () => setLang(lang === 'fr' ? 'en' : 'fr'));
  });
})();
